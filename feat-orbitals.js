/**
 * feat-orbitals.js
 * Phase 6 of the feature roadmap: 3D Orbital Visualization.
 *
 * Decided tech (recorded in the roadmap before this phase started): three.js
 * via CDN, with hand-built parametric point-cloud geometry for s/p/d/f
 * orbital lobes (rather than 3Dmol.js, which isn't suited to arbitrary
 * parametric surfaces). Loaded as a dynamic ES module import of three.js's
 * own module build, so no <script> tag or index.html change is needed —
 * the import happens inside mountOrbitals(), not at module load time.
 *
 * Rotation is a small hand-built pointer-drag rotator (not the OrbitControls
 * addon) to avoid pulling in a second CDN file for one feature.
 *
 * All orbital physics (radial wavefunctions, angular shapes, point-cloud
 * sampling) lives in orbital-math.js, which has no three.js/DOM dependency
 * and is unit-tested on its own — this file is the WebGL presentation layer.
 */

import { ORBITAL_LIBRARY, suggestedMaxRadius, generateOrbitalPointCloud } from './orbital-math.js';
import { moduleHeaderHTML } from './feat-helpers.js';

const THREE_CDN_URL = 'https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.module.js';

const GROUP_LABELS = { s: 's orbitals', p: 'p orbitals', d: 'd orbitals', f: 'f orbitals' };
const POSITIVE_COLOR = 0x4f8fff; // blue lobe (phase +)
const NEGATIVE_COLOR = 0xff5c7a; // red/pink lobe (phase -)
const NUCLEUS_COLOR = 0xffd24a;

export async function mountOrbitals(container) {
  container.innerHTML = moduleHeaderHTML(
    '⚛️',
    'Orbital Visualization',
    'Explore hydrogen-like s, p, d, and f orbitals as 3D electron-density point clouds. Drag to rotate, scroll to zoom.',
    '--accent-potassium'
  );

  container.insertAdjacentHTML('beforeend', `
    <div class="panel">
      <div class="form-grid" style="grid-template-columns: 1fr 1fr 1fr;">
        <div class="field">
          <label>Orbital</label>
          <select id="orb-select">
            ${['s', 'p', 'd', 'f'].map(g => `
              <optgroup label="${GROUP_LABELS[g]}">
                ${ORBITAL_LIBRARY.filter(o => o.group === g).map(o => `<option value="${o.id}" ${o.id === '2pz' ? 'selected' : ''}>${o.label}</option>`).join('')}
              </optgroup>
            `).join('')}
          </select>
        </div>
        <div class="field"><label>Point Count</label>
          <select id="orb-count">
            <option value="4000">4,000 (fast)</option>
            <option value="10000" selected>10,000</option>
            <option value="25000">25,000 (dense)</option>
          </select>
        </div>
        <div class="field"><label>Point Size</label>
          <input type="range" id="orb-size" min="0.03" max="0.25" step="0.01" value="0.08" />
        </div>
      </div>
      <div id="orb-status" class="text-muted" style="font-size: 0.85rem; min-height: 1.2em; margin-bottom: 8px;"></div>
      <div style="display:flex; gap: 16px; align-items:center; margin-bottom: 10px; font-size: 0.82rem;" class="text-muted">
        <span><span style="display:inline-block; width:10px; height:10px; border-radius:50%; background:#4f8fff; margin-right:4px;"></span>Positive phase</span>
        <span><span style="display:inline-block; width:10px; height:10px; border-radius:50%; background:#ff5c7a; margin-right:4px;"></span>Negative phase</span>
      </div>
      <div style="width: 100%; height: 480px; border: 1px solid var(--color-border); border-radius: var(--radius-sm); overflow: hidden; position: relative; background: #05070d;">
        <div id="orb-canvas-container" style="width:100%; height:100%; cursor: grab;"></div>
      </div>
      <p class="text-muted" style="font-size: 0.75rem; margin-top: 10px;">Point clouds are generated by sampling the hydrogen-like probability density |ψ|² (Bohr radius units) — not an isosurface mesh, so density itself (not just outline) is visible.</p>
    </div>
  `);

  const statusEl = document.getElementById('orb-status');
  const selectEl = document.getElementById('orb-select');
  const countEl = document.getElementById('orb-count');
  const sizeEl = document.getElementById('orb-size');
  const canvasContainer = document.getElementById('orb-canvas-container');

  let THREE;
  try {
    statusEl.textContent = 'Loading 3D engine...';
    THREE = await import(/* webpackIgnore: true */ THREE_CDN_URL);
  } catch (e) {
    statusEl.innerHTML = `<span style="color: var(--color-danger);">Could not load the 3D engine (three.js) from the CDN — check your network connection. (${e.message})</span>`;
    return;
  }

  // ── Scene setup ──────────────────────────────────────────────────────
  const scene = new THREE.Scene();
  const camera = new THREE.PerspectiveCamera(50, 1, 0.1, 1000);
  camera.position.set(0, 0, 30);

  const renderer = new THREE.WebGLRenderer({ antialias: true, alpha: false });
  renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 2));
  canvasContainer.appendChild(renderer.domElement);

  // Nucleus marker
  const nucleusGeom = new THREE.SphereGeometry(0.35, 16, 16);
  const nucleusMat = new THREE.MeshBasicMaterial({ color: NUCLEUS_COLOR });
  const nucleus = new THREE.Mesh(nucleusGeom, nucleusMat);
  scene.add(nucleus);

  const rotationGroup = new THREE.Group();
  scene.add(rotationGroup);

  let pointsMesh = null;

  function disposePointsMesh() {
    if (pointsMesh) {
      pointsMesh.geometry.dispose();
      pointsMesh.material.dispose();
      rotationGroup.remove(pointsMesh);
      pointsMesh = null;
    }
  }

  function buildOrbital(orbitalId, numPoints, pointSize) {
    const entry = ORBITAL_LIBRARY.find(o => o.id === orbitalId);
    if (!entry) return;
    statusEl.textContent = `Sampling ${numPoints.toLocaleString()} points for ${entry.label}...`;

    const maxRadius = suggestedMaxRadius(entry.n);
    const { points, acceptanceRate } = generateOrbitalPointCloud({
      entry, numPoints, maxRadius, seed: Date.now() % 1000000,
    });

    disposePointsMesh();

    const positions = new Float32Array(points.length * 3);
    const colors = new Float32Array(points.length * 3);
    const posColor = new THREE.Color(POSITIVE_COLOR);
    const negColor = new THREE.Color(NEGATIVE_COLOR);
    points.forEach((p, i) => {
      positions[i * 3] = p.x; positions[i * 3 + 1] = p.y; positions[i * 3 + 2] = p.z;
      const c = p.sign >= 0 ? posColor : negColor;
      colors[i * 3] = c.r; colors[i * 3 + 1] = c.g; colors[i * 3 + 2] = c.b;
    });

    const geometry = new THREE.BufferGeometry();
    geometry.setAttribute('position', new THREE.BufferAttribute(positions, 3));
    geometry.setAttribute('color', new THREE.BufferAttribute(colors, 3));
    const material = new THREE.PointsMaterial({ size: pointSize, vertexColors: true, transparent: true, opacity: 0.85, depthWrite: false });
    pointsMesh = new THREE.Points(geometry, material);
    rotationGroup.add(pointsMesh);

    camera.position.set(0, 0, maxRadius * 1.6);
    camera.far = maxRadius * 10;
    camera.updateProjectionMatrix();

    statusEl.textContent = `${entry.label}: ${points.length.toLocaleString()} points rendered (sampling efficiency ${(acceptanceRate * 100).toFixed(1)}%).`;
  }

  // ── Pointer-drag rotation (hand-built, no OrbitControls addon) ───────
  let isDragging = false;
  let lastX = 0, lastY = 0;
  canvasContainer.addEventListener('pointerdown', (e) => {
    isDragging = true;
    lastX = e.clientX; lastY = e.clientY;
    canvasContainer.style.cursor = 'grabbing';
  });
  window.addEventListener('pointerup', () => { isDragging = false; canvasContainer.style.cursor = 'grab'; });
  window.addEventListener('pointermove', (e) => {
    if (!isDragging) return;
    const dx = e.clientX - lastX, dy = e.clientY - lastY;
    lastX = e.clientX; lastY = e.clientY;
    rotationGroup.rotation.y += dx * 0.01;
    rotationGroup.rotation.x += dy * 0.01;
  });
  canvasContainer.addEventListener('wheel', (e) => {
    e.preventDefault();
    camera.position.z = Math.max(2, Math.min(camera.far * 0.9, camera.position.z * (1 + e.deltaY * 0.001)));
  }, { passive: false });

  // ── Resize handling ────────────────────────────────────────────────────
  function resize() {
    const w = canvasContainer.clientWidth || 300, h = canvasContainer.clientHeight || 300;
    renderer.setSize(w, h);
    camera.aspect = w / h;
    camera.updateProjectionMatrix();
  }
  const resizeObserver = typeof ResizeObserver !== 'undefined' ? new ResizeObserver(resize) : null;
  if (resizeObserver) resizeObserver.observe(canvasContainer);
  else window.addEventListener('resize', resize);
  resize();

  // ── Render loop ────────────────────────────────────────────────────────
  let rafId = null;
  function animate() {
    rafId = requestAnimationFrame(animate);
    renderer.render(scene, camera);
  }
  animate();

  // ── Controls wiring ───────────────────────────────────────────────────
  function rebuild() {
    buildOrbital(selectEl.value, parseInt(countEl.value), parseFloat(sizeEl.value));
  }
  selectEl.addEventListener('change', rebuild);
  countEl.addEventListener('change', rebuild);
  sizeEl.addEventListener('input', () => {
    if (pointsMesh) pointsMesh.material.size = parseFloat(sizeEl.value);
  });

  rebuild();

  // Expose a teardown hook in case the host app ever wants to stop the render loop
  // (the router currently mounts each module once and keeps it alive, so this is
  // defensive rather than required by the current navigation behavior).
  container._orbitalsTeardown = () => {
    if (rafId) cancelAnimationFrame(rafId);
    disposePointsMesh();
    if (resizeObserver) resizeObserver.disconnect();
    renderer.dispose();
  };
}
